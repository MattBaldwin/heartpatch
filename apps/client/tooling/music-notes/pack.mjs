/* global process, console, Buffer, URL */
// Packs the music's instrument notes (#664) into one file, so the game makes
// one download and one decode instead of 44 (on Linux WebKit every decode
// spins up its own pipeline). Dev tooling only:
// `node tooling/music-notes/pack.mjs <folder of single notes>`, with ffmpeg on
// the PATH. The folder holds `<instrument>-<note>.m4a` files (mono, trimmed,
// levelled; ASSETS.md says how). Writes src/audio/samples/music-notes.m4a and
// src/audio/music-notes.ts (where each note starts and how long it is).
import { execFileSync } from 'node:child_process';
import { readdirSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';

const RATE = 22_050;
/** Silence before the first note and between notes, so no note bleeds into the next. */
const GAP_S = 0.1;
const ORDER = ['piano', 'glock', 'marimba', 'harp', 'strings', 'bass', 'pizz', 'flute', 'shaker'];

const source = process.argv[2];
if (!source) throw new Error('usage: pack.mjs <folder of single notes>');
const here = path.dirname(new URL(import.meta.url).pathname);
const out = path.resolve(here, '../../src/audio/samples/music-notes.m4a');
const table = path.resolve(here, '../../src/audio/music-notes.ts');

const decode = (file) => {
  const bytes = execFileSync(
    'ffmpeg',
    ['-v', 'error', '-i', file, '-ac', '1', '-ar', String(RATE), '-f', 'f32le', '-'],
    {
      maxBuffer: 1 << 28,
    },
  );
  return new Float32Array(bytes.buffer, bytes.byteOffset, bytes.length / 4);
};

const files = readdirSync(source)
  .filter((f) => f.endsWith('.m4a'))
  .sort((a, b) => {
    const [ia, ib] = [a, b].map((f) => ORDER.indexOf(f.split('-')[0]));
    return ia - ib || a.localeCompare(b, 'en', { numeric: true });
  });
const gap = Math.round(GAP_S * RATE);
const parts = [];
const notes = [];
let at = gap;
for (const file of files) {
  const samples = decode(path.join(source, file));
  const [instrument, name] = file.replace('.m4a', '').split('-');
  notes.push({ instrument, name, start: at / RATE, length: samples.length / RATE });
  parts.push(samples);
  at += samples.length + gap;
}
const all = new Float32Array(at);
let cursor = gap;
for (const samples of parts) {
  all.set(samples, cursor);
  cursor += samples.length + gap;
}
const work = mkdtempSync(path.join(tmpdir(), 'music-notes-'));
const raw = path.join(work, 'notes.f32');
writeFileSync(raw, Buffer.from(all.buffer));
execFileSync('ffmpeg', [
  '-v',
  'error',
  '-y',
  '-f',
  'f32le',
  '-ar',
  String(RATE),
  '-ac',
  '1',
  '-i',
  raw,
  '-c:a',
  'aac',
  '-b:a',
  '56k',
  '-movflags',
  '+faststart',
  out,
]);
rmSync(work, { recursive: true });

/** As `leadIn` in music-samples.ts: the first sample above a whisper, less 2 ms. */
const packed = decode(out);
let first = 0;
while (first < packed.length && Math.abs(packed[first]) <= 0.002) first += 1;
const lead = Math.max(0, first / RATE - 0.002);

const rows = notes
  .map((n) => `  ['${n.instrument}', '${n.name}', ${n.start.toFixed(5)}, ${n.length.toFixed(5)}],`)
  .join('\n');
writeFileSync(
  table,
  `// Generated by tooling/music-notes/pack.mjs (#664): where each instrument note
// sits in samples/music-notes.m4a. Don't edit by hand; re-run the script.

/** [instrument, note, start (s), length (s)]. The file opens with ${GAP_S} s of silence. */
export const MUSIC_NOTES = [
${rows}
] as const;

/**
 * Where the file's first sound starts when decoded without encoder lead-in.
 * A decoder that keeps the lead-in shifts every note by the same amount.
 */
export const MUSIC_NOTES_LEAD_S = ${lead.toFixed(5)};
`,
);
console.log(`${String(files.length)} notes, ${(at / RATE).toFixed(1)} s -> ${out}`);
